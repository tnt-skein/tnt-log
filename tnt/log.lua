--- Журнал приложения поверх встроенного `log` Tarantool.
---
--- Писать, хранить, переоткрывать по SIGHUP, фильтровать по уровню
--- и выводить JSON умеет само ядро, и второй писатель рядом с ним не нужен.
--- Не умеет ядро другого: оно печатает пароль из поля как есть, пишет
--- `nan` литералом, режет запись длиннее ~16 КБ — сообщение-строку в JSON
--- внутри кавычек, с закрытой кавычкой и без NUL, а таблицу-запись с NUL
--- внутри и битым JSON, — в plain склеивает обрезанную запись со следующей
--- без перевода строки, бросает в вызывающего на кольце, на глубине 129
--- и на ключе-boolean, восемь имён вызывающего (`file`, `level`, `pid`,
--- `line`, `cord_name`, `fiber_name`, `fiber_id`, `error_msg`) молча
--- выбрасывает, а `time` и `module` дублирует рядом со своими. Всё это
--- проверено прогонами против голого `require('log')` на 3.8.0.
--- Фасад закрывает ровно это: прячет тайны, обезвреживает значения,
--- держит потолок записи, печатает plain одной строкой, подставляет поля
--- в сообщение по имени и подавляет повторы. И кладёт в каждую запись поля
--- контекста файбера (`tnt-context`): опознаватели запроса и трассы
--- верхними полями, прочие ключи объектом `context`. Всё остальное — дело
--- ядра.
---
--- **Настроек у пакета нет — ни `configure`, ни `default`, ни `status`.**
--- Это сознательное отступление от общего правила фасадов. У настройки
--- журнала один хозяин: встроенный журнал и раздел `log` конфигурации
--- кластера. Второй источник настроек в фасаде уже был и дал свои переменные
--- окружения уровня, вида и файла, которые не действовали ни дня: `configure()`
--- никто не звал, а `config:reload()` всё равно перезаписал бы заданное кодом. Фасад
--- только читает уровень — ради ранней отбраковки, а окончательно
--- фильтрует ядро.
---
--- **Тайны вырезаются здесь и до передачи в ядро, при любых обстоятельствах.**
--- Правило (`secret`, `scrub`) живёт здесь, а не у пакета отказов: тот
--- зависит от журнала, обратное невозможно, а две копии правила уже
--- разъезжались — журнал не приводил дефис к подчёркиванию, и `X-Api-Key`
--- в записи был виден. Ограничения правила названы вслух: тайна под безобидным именем
--- и без образца (`err = 'пароль hunter2 не подошёл'`) не ловится, а
--- `token=expired` в тексте прячется, хотя тайны в нём нет. Не ловятся
--- и закодированный запрос (`%3Ftoken%3D…`), и `/` или `@` внутри пароля
--- в адресе.
---
--- **Место вызова.** Ядро берёт `file`/`line` жёстко из третьего кадра
--- стека. Правдой они остаются только потому, что внутри фасада все вызовы
--- от метода журнала до ядра хвостовые: код после такого вызова или `pcall`
--- вокруг него перевели бы место всех записей внутрь этого файла.
---
--- **Подавление повторов сменило смысл.** Запись, отсечённая уровнем,
--- серию больше не рвёт и в счёт не идёт: прежде она рвала серию, хотя
--- в журнал не попадала, и следующая запись получала счётчик неизвестно
--- о чём.

