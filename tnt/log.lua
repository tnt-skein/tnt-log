---
--- Список отдаётся наружу нарочно. Прятать тайны приходится не только
--- журналу: то же делает пакет отказов, прежде чем показать причину
--- человеку. Две копии одного списка разъезжаются молча, и разъехавшийся
--- список — это дыра, которой не видит ни один гейт: поле, спрятанное
