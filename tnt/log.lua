---@class TntLogMemory
---@field answers table<string, boolean> Ответы по именам
---@field size integer Сколько имён помнится
---@field snapshot string[] Список, по которому давались ответы

--- Пустая память проверенных имён при данном снимке списка.
---@param snapshot string[]
---@return TntLogMemory
local function remembering(snapshot)
    return { answers = {}, size = 0, snapshot = snapshot }
end

--- Проверенные имена и снимок списка, по которому их проверяли.
---
--- Проверка имени — перевод в нижний регистр, замена и девять поисков
--- подстроки; на пяти полях записи это полторы микросекунды из девяти.
--- Память делает её в десять раз дешевле, но только пока список не менялся:
--- поэтому снимок сверяется со списком поэлементно перед каждой записью.
local memory = remembering({})

--- Сверяет список имён со снимком и забывает проверенное, если он менялся.
---
--- Поэлементно, а не по ссылке на таблицу: `table.insert` и правка элемента
--- на месте ссылку не меняют, а имя, уже проверенное по прежнему списку,
--- иначе осталось бы в памяти с прежним ответом.
local function sync_hints()
    local hints = Module.secret_hints
    local same = #hints == #memory.snapshot

    if same then
        for position, hint in ipairs(hints) do
            if hint ~= memory.snapshot[position] then
                same = false

                break
            end
        end
    end

    if same then
        return
    end

    local snapshot = {}

    for position, hint in ipairs(hints) do
        snapshot[position] = hint
    end

    memory = remembering(snapshot)
end

--- Есть ли в тексте подсказка тайны — по снимку и без памяти.
---
--- Сверяется вхождение подстроки, а не конец имени: в поле `db_password`
--- секрет ровно такой же, как в `password`, а в `x_token_x` — такой же,
--- как в `token`. Лишняя заглушка стоит одного вопроса «а что там было»,
--- утечка стоит учётной записи.
---
--- Дефис считается за подчёркивание. Список писался под имена полей
--- (`api_key`), а сюда приходят ещё и имена заголовков (`X-Api-Key`)
--- и параметров запроса: без приведения ключ в заголовке уезжал бы
--- наружу, а в поле — нет.
---@param text string
---@return boolean
local function mentions_hint(text)
    local shown = text:lower():gsub('%-', '_')

    for _, hint in ipairs(memory.snapshot) do
        -- Поиск подстроки, а не по образцу: имена в списке пишет человек,
        -- и знак вроде точки в них значил бы «любой знак». Начало поиска —
        -- умолчание: единица и ноль значат здесь одно и то же.
        if shown:find(hint, nil, true) ~= nil then
            return true
        end
    end

    return false
end

--- Похоже ли имя на тайну — по снимку, с памятью на короткие имена.
---
--- Помнятся только строки не длиннее `MEMO_NAME_LIMIT`. Число или таблица
--- в роли имени приходят редко, а ключ-таблица держал бы в памяти чужой
--- объект. Длинная строка в роли имени — это данные, а не имя поля:
--- тысяча таких держала бы мегабайты и вытесняла бы из памяти настоящие
--- имена, ради которых память и заведена.
---@param name any
---@return boolean
local function looks_secret(name)
    local known = memory.answers[name]

    if known ~= nil then
        return known
    end

    local found = mentions_hint(tostring(name))

    if type(name) == 'string' and #name <= MEMO_NAME_LIMIT then
        if memory.size == MEMO_LIMIT then
            memory = remembering(memory.snapshot)
        end

        memory.answers[name] = found
        memory.size = memory.size + 1
    end

    return found
end

--- Похоже ли имя на тайну.
---@param name any
---@return boolean
function Module.secret(name)
    sync_hints()

    return looks_secret(name)
end

--- Адрес с учётными данными: `схема://логин:пароль@узел`.
---
--- Схема не проверяется: за `://` следят и придуманные схемы, а нужен
--- здесь только пароль. Логин допускается пустым — `http://:слово@узел`
--- встречается, — а пароль нет: двоеточие, за которым сразу `@`,
--- означает, что пароля в адресе не было вовсе.
---
--- Косая черта не входит ни в логин, ни в пароль, и это не придирка:
--- без неё `http://узел:3301/записи@главная` разбирается как пароль
--- `3301/записи`, и вместо тайны прячется порт.
local CREDENTIALS = '(://[^:@/%s]*:)[^@/%s]+(@)'

--- Знаки, на которых кончается слово: пробел, кавычки, скобки, `@`,
--- запятая и точка с запятой. Косой черты, двоеточия и равенства среди
--- них нет.
local DELIMITERS = '%s@,;%(%)%[%]{}"\''

--- Учётные данные без схемы: `логин:пароль@узел`.
---
--- Так адрес пишут репликация и advertise (`replicator:слово@127.0.0.1:3301`),
--- и так он попадает в текст отказа: «connect to storage:слово@10.0.0.5
--- failed». Логин начинается с начала слова — после пробела, кавычки,
--- скобки или запятой (`%f` — переход от разделителя к знаку слова).
--- Косая черта и двоеточие разделителем не считаются, и в этом весь
--- смысл: `узел/записи:7@главная` — путь, а не логин с паролем, а после
--- двоеточия внутри `a:b:c` новое слово не начинается — иначе образец
--- заходил бы в строку заново с каждого двоеточия.
---
--- Пароль идёт до `@` и может содержать двоеточие и `=`; разделители его
--- обрывают. Любой разделитель в пароль не входит, поэтому ни одно слово
--- не начинается внутри пароля, и образец идёт за линейное время. Равенство
--- по той же причине не разделитель: оно входит в пароль, и с ним среди
--- разделителей `@a:=a:=…` без `@` в конце перебиралось бы заново с каждого
--- `=` — восемь килобайт шли бы секунды. Цена — логин `uri=storage`
--- в `uri=storage:слово@узел`; пароль прячется так же.
---
--- Ложных срабатываний на обычном тексте журнала нет: время `12:30`, IPv6
--- `[fe80::1]:3301`, `user@host`, пути и «ERROR: …» образцу не подходят —
--- ему нужны двоеточие и `@` за непустым паролем без пробела. Лишнее он
--- прячет в `mailto:ivan@example.org`: по виду это то же самое.
local BARE_CREDENTIALS = '%f[^%z' .. DELIMITERS .. ']([^' .. DELIMITERS .. ':/]+:)[^%s@,;%(%)%[%]{}"\'/]+(@)'

--- Знаки, которых нет в имени пары «имя=значение» и «имя: значение».
---
--- Только те, что кончают имя на деле: пробел, разделители пары, границы
--- параметров запроса и кавычки. Скобки, запятая и косая черта в имени
--- остаются: `secret(1)=…`, `token/x=…` и `1,token=…` — такие же тайны,
--- как `token=…`, а имя сверяется по вхождению подсказки.
local NOT_NAME = '%s=:&;%?\'"'

--- Знак имени пары.
local PAIR_NAME_CHAR = '[^' .. NOT_NAME .. ']'

--- Начало пары: имя, разделитель и место, где начинается значение.
---
--- Имя пары — целое слово. Слово берётся от начала (`%f`), а не с любой
--- позиции: с любой позиции образец перебирал бы каждый хвост длинного
--- слова и шёл квадратично.
---
--- Повтор знаков имени записан как «знак и ещё сколько-то», а не `+`, хотя
--- значат они одно. Переход `%f` уже поставил начало на знак имени, и `*`
--- или `-` на месте `+` захватили бы то же имя — такую поломку не заметила
--- бы ни одна проверка. У этой записи поломка заметна: с `+` вместо `*`
--- образец не видит имени из одного знака, а подсказку из одной буквы
--- приложение задать вправе.
---
--- Разделитель — равенство или двоеточие, пробелы вокруг и кавычка,
--- закрывающая имя (`"password":`). Значение образец не берёт: где оно
--- кончается, решает `value_of`, и только для имени-тайны.
local PAIR = '%f[^%z' .. NOT_NAME .. '](' .. PAIR_NAME_CHAR .. PAIR_NAME_CHAR .. '*)["\']?%s*[=:]%s*()'

--- Значение без кавычек: до пробела, `&`, `;` или кавычки.
---
--- Запятая, скобки и равенство значение не обрывают: в `password=hun,ter2`
--- пароль — `hun,ter2`, и спрятать его до запятой значит показать хвост.
local BARE_VALUE = '^[^%s&;"\']*'

--- Остаток строки текста: до перевода строки или возврата каретки.
local LINE = '^[^\r\n]*'

--- Слово за словом схемы в заголовке авторизации: сам токен.
---
--- Пробел за словом схемы записан как `%s%s*`, а не `%s+`, хотя значат они
--- одно. Слово схемы уже кончилось на пробеле или разделителе, и `%s*`
--- на месте `%s+` не нашёл бы ничего лишнего — такую поломку не заметила
--- бы ни одна проверка. У `%s%s*` поломка заметна: `%s%s+` требует двух
--- пробелов.
local SCHEME_TOKEN = '^%s%s*[^%s&;"\']+'

--- Слова схем авторизации (`X-Token: Bearer abc`), в нижнем регистре.
---
--- За словом схемы идёт сам токен, и прятать надо оба: иначе спряталось бы
--- слово `Bearer`, а токен остался бы на виду. Под именем с `authorization`
--- список не нужен: там значение прячется до конца строки.
local SCHEMES = { basic = true, bearer = true, digest = true, negotiate = true, ntlm = true, token = true }

--- Код обратной косой черты: ею экранируют кавычку.
local BACKSLASH = ('\\'):byte()

--- Где кончается значение в кавычках, начатое с позиции `first`.
---
--- Закрывает не всякая такая же кавычка, а только та, перед которой столько
--- обратных косых, сколько у открывающей, — с точностью до пар, которыми
--- экранирована сама косая. У простой кавычки перед закрывающей чётное
--- число косых: в `"hun\"ter2"` кавычка после `hun` экранирована и значение
--- не закрывает, а в `"a\\"` закрывает. У экранированной (JSON строкой
--- внутри JSON) закрывающей предшествует одна косая по модулю четырёх:
--- три косые — это экранированная кавычка внутреннего значения. Иначе
--- значение кончалось бы на экранированной кавычке, и хвост пароля
--- уезжал бы в запись.
---
--- Косые считаются назад от найденной кавычки, но не дальше начала значения:
--- каждая косая считается при одной кавычке, и поиск идёт за линейное время.
---@param text string
---@param quote string Открывающая кавычка, с косой или без
---@param first integer
---@return integer|nil last Последний знак значения; nil, если не закрыто
local function closed_at(text, quote, first)
    local mark = quote:sub(-1)
    local from = first

    while true do
        -- Без признака поиска подстроки: кавычка в образце значит себя.
        local found = text:find(mark, from)

        if found == nil then
            return nil
        end

        local before = found - 1

        while before >= first and text:byte(before) == BACKSLASH do
            before = before - 1
        end

        if (found - 1 - before) % (2 * #quote) == #quote - 1 then
            return found - #quote
        end

        from = found + 1
    end
end

--- Где лежит значение пары, начатое с позиции `at`.
---
--- Значение в кавычках — до закрывающей кавычки (`closed_at`). Незакрытая
--- кавычка (`password="abc` или кавычка, закрытая за окном) прячет всё
--- до конца строки: иначе уцелело бы второе слово пароля.
---
--- Значение под именем с `authorization` без кавычек прячется до конца
--- строки текста, вместе со словом схемы. Схем много — `Bearer`, `Basic`,
--- `OAuth`, `ApiKey`, `Bot`, свои у каждого сервиса, — и список схем
--- однажды не узнал бы новую и показал бы токен. Потеря слова схемы
--- дешевле утечки; следующая строка текста остаётся на виду.
---
--- Прочее значение без кавычек — до `BARE_VALUE`; за словом схемы к нему
--- прибавляется токен (`X-Token: Bearer abc`).
---@param text string
---@param at integer
---@param name string Имя пары
---@return integer first
---@return integer last Меньше first, если значение пустое
local function value_of(text, at, name)
    local quote = text:match('^\\?["\']', at)

    if quote ~= nil then
        local first = at + #quote

        return first, closed_at(text, quote, first) or #text
    end

    -- Без признака поиска подстроки: в слове нет знаков образца.
    if name:lower():find('authorization') ~= nil then
        local _, line_end = text:find(LINE, at)

        ---@cast line_end integer

        return at, line_end
    end

    -- Образец со звёздочкой совпадает всегда, хотя бы пустой строкой.
    local _, last = text:find(BARE_VALUE, at)

    ---@cast last integer

    if SCHEMES[text:sub(at, last):lower()] then
        local _, token = text:find(SCHEME_TOKEN, last + 1)

        last = token or last
    end

    return at, last
end

--- Прячет значения пар, чьё имя похоже на тайну.
---
--- Значение пары с безобидным именем не поглощается: поиск следующей пары
--- идёт сразу за разделителем. Иначе `url=https://h/?token=abc` целиком
--- сошло бы за значение `url`, и токен в нём уцелел бы. Значение тайны,
--- наоборот, пропускается целиком: пара внутри спрятанного уже спрятана.
---@param text string
---@return string
local function hide_pairs(text)
    ---@type string[]|nil
    local pieces = nil
    -- Начало непереписанного куска — отрицательным отсчётом от конца, то
    -- есть первым байтом: у единицы мутанты `0` и `1-1` давали тот же срез
    -- и то же сравнение с местом значения (оно не меньше единицы), а у
    -- `-#text` единственный мутант `+#text` не проходит загрузку. Пустая
    -- строка пар не содержит, и до срезов дело не доходит.
    local copied = -#text

    for name, at in text:gmatch(PAIR) do
        -- Значение, начатое внутри спрятанного, — часть спрятанного.
        -- Начатое ровно за ним — уже новое: в `Cookie: token="два слова"`
        -- значение `Cookie` кончается перед кавычкой, а с неё начинается
        -- значение `token`.
        if at >= copied and mentions_hint(name) then
            -- Пустые скобки в образце захватывают место, а не текст.
            local first, last = value_of(text, at --[[@as integer]], name)

            if first <= last then
                pieces = pieces or {}
                table.insert(pieces, text:sub(copied, first - 1))
                table.insert(pieces, Module.HIDDEN)
                copied = last + 1
            end
        end
    end

    -- Без единой спрятанной пары строка отдаётся та же: собирать её заново
    -- из кусков значило бы переписать строку ради ничего.
    if pieces == nil then
        return text
    end

    table.insert(pieces, text:sub(copied))

    return table.concat(pieces)
end

--- Прячет тайны внутри строки — по снимку, без сверки со списком.
---
--- Хост, порт и логин остаются на виду: по ним человек и понимает, куда
--- ходил узел, а без них отказ «соединение не открылось» не говорит
--- ничего. Имена параметров тоже остаются: скрывается значение.
---
--- Пары прячутся раньше адресов, и порядок не случаен. Образец адреса без
--- схемы видит в `db:password=P@ss` логин `db` и пароль `password=P`
--- до `@`: спрятав его первым, он съел бы имя пары, и `ss` за `@` ушёл бы
--- в запись. Пара, спрятанная первой, адресу ничего не оставляет, а адрес
--- внутри безобидной пары (`url=postgres://root:слово@db`) пары не трогают.
---
--- Образцы гоняются только по строке, где им есть за что зацепиться: почти
--- все значения в записи — имена узлов и числа, и три прохода образцом
--- по каждому стоили бы дороже самой записи. Предпроверки на результат
--- не влияют — только на цену, и проверки следят за ней счётом вызовов.
---@param text string
---@return string
local function scrubbed(text)
    -- Без двоеточия нет ни адреса, ни заголовка: две проверки из трёх
    -- на обычной строке не делаются вовсе.
    local colon = text:find(':') ~= nil

    -- Пара прячется только под именем-тайной, а имя — кусок той же строки:
    -- если подсказки нет во всей строке, её нет ни в одном имени, и искать
    -- пары незачем. На адресе без тайн поиск стоил бы дороже всей записи.
    -- Строка сверяется без памяти: память держала бы сами строки.
    if (colon or text:find('=') ~= nil) and mentions_hint(text) then
        text = hide_pairs(text)
    end

    if colon then
        if text:find('://') ~= nil then
            text = text:gsub(CREDENTIALS, '%1' .. Module.HIDDEN .. '%2')
        end

        if text:find('@') ~= nil then
            text = text:gsub(BARE_CREDENTIALS, '%1' .. Module.HIDDEN .. '%2')
        end
    end

    return text
end

---@class TntLogWalk
---@field raw integer Грубая оценка размера записи
---@field truncated boolean Что-то урезано
---@field overflow boolean Обход остановлен: запись заведомо велика
---@field seen table<table, boolean> Таблицы, внутри которых мы сейчас находимся

--- Состояние обхода одной записи.
---@return TntLogWalk
local function fresh()
    return { raw = 0, truncated = false, overflow = false, seen = {} }
end

--- Учитывает в оценке размера одно значение: число, boolean, null, таблицу.
---
--- Место учёта одно на все роды значений: разойдись цена числа в двух
--- местах, оценка ручалась бы за размер только наполовину.
---@param state TntLogWalk
local function count(state)
    state.raw = state.raw + PIECE
end

--- Учитывает строку в оценке размера и отдаёт её.
---@param text string
---@param state TntLogWalk
---@return string
local function note(text, state)
    count(state)
    state.raw = state.raw + #text

    return text
end

--- Строка, пригодная для JSON: вместо невалидного UTF-8 — сколько там было.
---
--- Сырые байты ядро пропускает как есть, и строгий разборщик на такой
--- записи падает целиком — вместе с полями, в которых всё было в порядке.
---@param text string
---@return string
local function readable(text)
    if utf8.len(text) == nil then
        return ('[не UTF-8, %d байт]'):format(#text)
    end

    return text
end

--- Обрезает строку по границе знака.
---
--- Граница ищется назад от потолка: байт продолжения UTF-8 (от 0x80
--- до 0xBF) не может начинать знак, и срез перед ним разорвал бы «я»
--- пополам — то есть сделал бы из валидной строки невалидную.
---
--- Назад — не дальше трёх байт: знак UTF-8 не длиннее четырёх. Строку,
--- которую никто не сверял с UTF-8 (её режет `scrub`), байты продолжения
--- могут заполнять до самого начала, и поиск без предела ушёл бы за него.
---@param text string
---@param limit integer
---@param state TntLogWalk
---@return string
local function cut(text, limit, state)
    if #text <= limit then
        return text
    end

    local stop = limit
    local next_byte = text:byte(stop + 1)

    while stop > limit - 3 and next_byte >= 0x80 and next_byte <= 0xBF do
        stop = stop - 1
        next_byte = text:byte(stop + 1)
    end

    state.truncated = true

    -- Начало среза — отрицательным отсчётом: у `sub(1, stop)` мутанты `0`
    -- и `1-1` дают ту же строку. Строка здесь длиннее потолка, и срез
    -- от `-#text` начинается с первого байта.
    return text:sub(-#text, stop) .. CUT
end

--- Очищенная строка-значение: UTF-8, тайны, потолок.
---
--- Тайны прячутся до обрезки: пароль, попавший на границу, иначе ушёл бы
--- в запись половиной, которую образец уже не узнает. Но не дальше окна.
---@param text string
---@param state TntLogWalk
---@return string
local function clean_string(text, state)
    local windowed = cut(readable(text), SCRUB_WINDOW, state)

    return note(cut(scrubbed(windowed), STRING_LIMIT, state), state)
end

--- Знаки имени в заполнителе: латиница, цифры, подчёркивание и точка,
--- как в PSR-3. Сообщение с другими фигурными скобками — обрывок JSON,
--- шаблон, кусок кода — заполнителем не считается и остаётся как есть.
local NAME_CHARS = 'A-Za-z0-9_%.'

--- Заполнитель в сообщении: имя поля в фигурных скобках.
---
--- Точка ведёт во вложенную таблицу полей (`{db.host}`); первый сегмент —
--- ключ верхнего уровня. Имя записано как первый знак и хвост `[…][…]*`,
--- а не `[…]+`, хотя значат они одно. `+` неотличим от `*`: пустое имя
--- и так остаётся дословно — поля под ним нет, — и поломку повтора
--- не заметила бы ни одна проверка. У `[…][…]*` поломка заметна:
--- `[…][…]+` требует двух знаков и теряет `{a}`.
local PLACEHOLDER = '{([' .. NAME_CHARS .. '][' .. NAME_CHARS .. ']*)}'

--- Значение поля по пути через точку: `{db.host}` — `fields.db.host`.
---
--- Сегмент ищется строкой, а не найдя — числом: у очищенной копии
--- массива ключи остались числами, и `{peers.1}` — его первый элемент.
--- Пустой сегмент (`{a..b}`, `{.a}`) пути не составляет; за ним, как
--- за любым несуществующим путём, — пусто, и заполнитель остаётся
--- дословно. Отсутствие сверяется родом, а не с `nil`: `box.NULL` равен
--- `nil`, а в сообщение он должен уходить словом `null`.
---@param fields table
---@param path string
---@return any
local function field_at(fields, path)
    local value = fields

    for segment in ('.' .. path):gmatch('%.([^%.]*)') do
        if segment == '' or type(value) ~= 'table' then
            return nil
        end

        local inner = value[segment]

        if type(inner) == 'nil' then
            inner = value[tonumber(segment)]
        end

        value = inner
    end

    return value
end

--- Чем заменить заполнитель, если под именем есть очищенное поле.
---
--- Строка подставляется как есть, прочее — как в JSON: число и boolean
--- своим словом, `box.NULL` — `null`, таблица — JSON своей очищенной
--- копии. Пусто, если поля нет: `gsub` тогда оставляет заполнитель
--- дословно, как велит PSR-3, и сообщение с чужими скобками не портится.
---@param fields table
---@param name string
---@return string|nil
local function replacement(fields, name)
    local value = field_at(fields, name)

    if type(value) == 'nil' then
        return nil
    end

    if type(value) == 'string' then
        return value
    end

    return measure.encode(value)
end

--- Сообщение с подставленными заполнителями.
---
--- Значения берутся из уже очищенных полей: `{password}` даёт `[скрыто]`,
--- а `{obj}` с кольцом — копию с `[кольцо]` внутри. Поле при этом
--- остаётся в `fields`: по нему ищут в сборщике. Подставленное второй раз
--- не разбирается — `gsub` идёт по тексту один раз.
---@param message string Текст после вырезания тайн
---@param fields table Очищенные поля
---@return string
local function filled(message, fields)
    return (message:gsub(PLACEHOLDER, function(name)
        return replacement(fields, name)
    end))
end

--- Прячет тайны внутри строки. Не строка возвращается как есть.
---
--- Строка длиннее окна обрезается по нему и помечается `…`: за окном
--- образцы не ходят, а отдать непроверенный хвост значило бы отдать
--- тайну, которая в нём лежит.
---@param value any
---@return any
function Module.scrub(value)
    if type(value) ~= 'string' then
        return value
    end

    sync_hints()

    return scrubbed(cut(value, SCRUB_WINDOW, fresh()))
end

--- Что напечатал `tostring`, если он дал строку.
---
--- Чужой `__tostring` вправе бросить, а в LuaJIT — и вернуть не строку:
--- таблицу, чья собственная печать бросает. Журнал бросать не вправе,
--- поэтому печать идёт под `pcall`, а не строка считается отказом печати.
---@param value any
---@return string|nil
local function printed(value)
    local ok, shown = pcall(tostring, value)

    if ok and type(shown) == 'string' then
        return shown
    end

    return nil
end

--- Очищенный ключ.
---
--- Целое число остаётся числом, пока double хранит его точно: массив должен
--- остаться массивом, а целое вне ±2^53 ядро ключом не принимает и бросает.
--- Прочее становится строкой — ядро на ключе-boolean бросает. Ключ идёт
--- через те же тайны и потолок, что и значение: адрес с паролем в роли
--- ключа — такая же утечка, как в роли значения, и не короче его.
---
--- Вторым отдаётся имя ключа до очистки: по нему и решается, похоже ли
--- имя на тайну. По очищенному нельзя — обрезка по потолку отрезала бы
--- подсказку в конце длинного имени. По исходному ключу тоже нельзя —
--- ключ-таблица с `__tostring`, печатающим `password`, в записи выглядит
--- как `password`, и значение под ним должно быть спрятано так же.
---@param key any
---@param state TntLogWalk
---@return any name
---@return string|nil shown Имя до очистки; nil, если ключ остался числом
local function clean_key(key, state)
    local kind = type(key)

    -- Остаток от деления на единицу у бесконечности — не число, и она
    -- уходит строкой вместе с дробными.
    if kind == 'number' and key % 1 == 0 and key >= -EXACT_INTEGER and key <= EXACT_INTEGER then
        count(state)

        return key, nil
    end

    local shown = key

    if kind ~= 'string' then
        shown = printed(key) or '[' .. kind .. ']'
    end

    return clean_string(shown, state), shown
end

--- Копия таблицы, у которой все ключи — строки.
---
--- Ядро кодирует таблицу со строковыми и числовыми ключами как объект,
--- и `1` рядом с `'1'` дали бы два одинаковых ключа в одном объекте.
--- Здесь они сливаются в один: это честнее, чем запись, которую строгий
--- разборщик читает по-разному.
---@param copy table
---@return table
local function with_string_keys(copy)
    local named = {}

    for key, inner in pairs(copy) do
        named[tostring(key)] = inner
    end

    return named
end

---@type fun(value: any, depth: integer, state: TntLogWalk): any, boolean|nil
local walk

--- Обходит результат `__serialize`.
---
--- Переход через `__serialize` считается уровнем: `__serialize`, отдающий
--- новую таблицу со своей же метатаблицей, иначе уводил бы обход
--- в бесконечность, минуя и отметку кольца, и предел глубины.
---@param value any
---@param serialize function
---@param depth integer
---@param state TntLogWalk
---@return boolean ok
---@return any shown
---@return boolean|nil numbered
local function serialized(value, serialize, depth, state)
    -- Предел проверяется и здесь, а не только у обычной таблицы:
    -- `__serialize`, отдающий новый объект своего же рода, до обычной
    -- таблицы не доходит никогда, и обход ушёл бы в переполнение стека.
    if depth > MAX_DEPTH then
        state.truncated = true

        return true, note(DEEP, state)
    end

    local ok, shown = pcall(serialize, value)
    local numbered = nil

    if ok then
        state.seen[value] = true
        shown, numbered = walk(shown, depth + 1, state)
        state.seen[value] = nil
    end

    return ok, shown, numbered
end

--- Копия обычной таблицы.
---@param value table
---@param depth integer
---@param state TntLogWalk
---@return any copy Копия либо метка глубины
---@return boolean|nil numbered Есть ли в копии числовые ключи
local function copy_table(value, depth, state)
    if depth > MAX_DEPTH then
        state.truncated = true

        return note(DEEP, state)
    end

    state.seen[value] = true
    count(state)

    local copy = {}
    ---@type boolean|nil
    local named
    ---@type boolean|nil
    local numbered

    for key, inner in pairs(value) do
        if state.raw > RECORD_LIMIT then
            state.overflow = true

            break
        end

        local name, shown = clean_key(key, state)

        if shown == nil then
            numbered = true
        else
            named = true
        end

        -- Значение под именем тайны заменяется целиком, со всем поддеревом:
        -- обходить то, что всё равно не покажем, незачем.
        if shown ~= nil and looks_secret(shown) then
            copy[name] = note(Module.HIDDEN, state)
        else
            copy[name] = walk(inner, depth + 1, state)
        end
    end

    -- Отметка снимается на выходе: кольцо — это ссылка на таблицу, внутри
    -- которой мы сейчас находимся, а не вторая ссылка на одну и ту же
    -- таблицу из соседних полей. Второе законно и прятать его нечего.
    state.seen[value] = nil

    if named and numbered then
        return with_string_keys(copy)
    end

    return copy, numbered
end

--- Очищенная копия таблицы.
---@param value table
---@param depth integer
---@param state TntLogWalk
---@return any shown
---@return boolean|nil numbered
local function walk_table(value, depth, state)
    if state.seen[value] then
        return note(Module.CYCLE, state)
    end

    local meta = getmetatable(value)

    -- Метатаблица читается мимо её собственной метатаблицы: чужой `__index`
    -- на ней мог бы бросить, а журнал бросать не вправе.
    if type(meta) == 'table' then
        local serialize = rawget(meta, '__serialize')

        if type(serialize) == 'function' then
            local ok, shown, numbered = serialized(value, serialize, depth, state)

            if not ok then
                return clean_string('[__serialize бросил]', state)
            end

            return shown, numbered
        end

        if rawget(meta, '__tostring') ~= nil then
            return clean_string(printed(value) or '[__tostring бросил]', state)
        end
    end

    return copy_table(value, depth, state)
end

--- Очищенное значение 64-битного целого или прочего cdata.
---@param value any
---@param state TntLogWalk
---@return any
local function walk_cdata(value, state)
    -- Пустой указатель, в том числе `box.NULL`: в JSON это null.
    if value == nil then
        count(state)

        return value
    end

    if ffi.istype('int64_t', value) or ffi.istype('uint64_t', value) then
        -- Нижняя граница — только у знакового: LuaJIT переводит -2^53
        -- в uint64_t приведением отрицательного double, а это
        -- неопределённое поведение C. На x86 выходит мусор, и проверка
        -- ложна для любого ULL; на arm64 — ноль, и ошибки не видно.
        if value <= EXACT_INTEGER and (ffi.istype('uint64_t', value) or value >= -EXACT_INTEGER) then
            count(state)

            return tonumber(value)
        end

        -- Строкой: голое число ядро пишет как есть, и разборщик на double
        -- меняет в нём последние цифры.
        return clean_string((tostring(value):gsub('U?LL$', '')), state)
    end

    return clean_string(printed(value) or '[cdata]', state)
end

--- Очищенное значение userdata.
---@param value any
---@param depth integer
---@param state TntLogWalk
---@return any shown
---@return boolean|nil numbered
local function walk_userdata(value, depth, state)
    local meta = getmetatable(value)

    if type(meta) == 'table' then
        local serialize = rawget(meta, '__serialize')

        if type(serialize) == 'function' then
            local ok, shown, numbered = serialized(value, serialize, depth, state)

            if ok then
                return shown, numbered
            end
        end
    end

    return clean_string(printed(value) or '[userdata]', state)
end

--- Очищенная копия значения.
---
--- Итог — только строки, конечные числа, boolean, null и таблицы из них:
--- на этом `json.encode` ядра не бросает и строгий разборщик не спотыкается.
---@param value any
---@param depth integer
---@param state TntLogWalk
---@return any shown
---@return boolean|nil numbered
walk = function(value, depth, state)
    local kind = type(value)

    if kind == 'string' then
        return clean_string(value, state)
    end

    if kind == 'number' then
        count(state)

        -- Ядро пишет их литералами, и строгий JSON на такой записи падает.
        if value ~= value then
            return 'nan'
        end

        if value == math.huge then
            return 'inf'
        end

        if value == -math.huge then
            return '-inf'
        end

        return value
    end

    if kind == 'boolean' then
        count(state)

        return value
    end

    if kind == 'table' then
        return walk_table(value, depth, state)
    end

    if kind == 'cdata' then
        return walk_cdata(value, state)
    end

    if kind == 'userdata' then
        return walk_userdata(value, depth, state)
    end

    return clean_string('[' .. kind .. ']', state)
end

--- Очищенные аргументы, переданные после полей.
---
--- Прежде второй аргумент после полей выбрасывался молча, и `('%s %d', 'a', 1)`
--- теряло единицу — вопреки обещанию «ничего не теряется». Аргументы идут
--- полем уровня записи, а не внутрь `fields`: у полей вызывающего занятых
--- имён нет, и это обещание держится.
---
--- Массив строится по числу аргументов, а не по `{...}`: `nil` среди них
--- в таблице стал бы дырой и сдвинул бы позиции, а строкой `[nil]` он
--- стоит на своём месте. Остановки по оценке здесь нет: аргументов не больше,
--- чем помещается в вызов, и каждый ограничен своими потолками, а решает
--- итоговая оценка записи.
---@param state TntLogWalk
---@param ... any
---@return any[]
local function walk_args(state, ...)
    local args = {}

    count(state)

    for position = 1, select('#', ...) do
        args[position] = walk((select(position, ...)), 1, state)
    end

    return args
end

--- Кладёт в запись очищенные поля контекста: опознаватели запроса
--- и трассы верхними полями, прочие ключи объектом `context`.
---
--- Верхними — потому что так велит приложение OpenTelemetry о следах
--- трассы в журналах не-OTLP, и так их ищут сборщики; объектом — потому
--- что ключи приложения на верху записи столкнулись бы и с полями фасада,
--- и с полями ядра, которые ядро молча выбрасывает или дублирует.
--- Значения прошли те же тайны и потолки, что `fields`: `request_id`,
--- пришедший из заголовка клиента, — не своё.
---@param record TntLogRecord
---@param shown any Очищенная копия полей контекста
local function attach(record, shown)
    if type(shown) ~= 'table' then
        return
    end

    for _, name in ipairs(context.LOG_TOP) do
        record[name] = shown[name]
    end

    -- Объект `context` — только таблицей: пары из не-таблицы plain
    -- не соберёт, а журнал бросать не вправе.
    if type(shown.context) == 'table' then
        record.context = shown.context
    end
end

--- Собирает запись: сообщение, поля, лишние аргументы, поля контекста, имя
--- инстанса, отметку урезания.
---
--- Текст сообщения проходит окно и тайны до обхода полей, а заполнители
--- и потолок строки — после него: заполнители берут значения из очищенных
--- полей, сообщение от них может вырасти, и потолок с отметкой `truncated`
--- применяется к итогу; в оценку размера сообщение идёт уже итоговое.
--- Порядок не случаен. Обход полей — цикл `pairs`, который LuaJIT
--- не компилирует, и запись, начинавшаяся с него, стоила под JIT на 0,3 мкс
--- дороже (2,3 против 2,0 мкс): трассы рвались на входе, и строковая
--- работа над сообщением шла в интерпретаторе. Перед обходом она остаётся
--- скомпилированной. Обход широкой таблицы останавливается по оценке одних
--- полей — сообщение не длиннее потолка строки, и на остановке это
--- не сказывается.
---@param msg any
---@param fields any
---@param instance_name string|nil
---@param ambient table|nil Поля контекста файбера
---@param ... any Аргументы после полей
---@return TntLogRecord
local function build(msg, fields, instance_name, ambient, ...)
    sync_hints()

    local state = fresh()
    local text = msg
    local textual = type(msg) == 'string'

    if not textual then
        -- Сообщение-таблица меряется отдельно: в запись оно ляжет строкой,
        -- и в оценку пойдёт уже она.
        local scratch = fresh()
        local shown = walk(msg, 1, scratch)

        text = type(shown) == 'table' and measure.encode(shown) or tostring(shown)
        state.truncated = scratch.truncated or scratch.overflow
    end

    local message = scrubbed(cut(readable(text), SCRUB_WINDOW, state))
    local record = {}

    -- Контекст обходится раньше полей: он мал, а поля бывают широки, и обход,
    -- вставший на них по оценке, иначе не дошёл бы до опознавателей —
    -- запасная запись о широкой таблице осталась бы без `request_id`.
    if ambient ~= nil then
        attach(record, walk(ambient, 1, state))
    end

    if fields ~= nil then
        local shown, numbered = walk(fields, 1, state)

        if type(shown) ~= 'table' then
            record.fields = { value = shown }
        elseif next(shown) ~= nil then
            record.fields = numbered and with_string_keys(shown) or shown
        end
    end

    if select('#', ...) > 0 then
        record.args = walk_args(state, ...)
    end

    -- Заполнители — только в сообщении-строке: JSON копии таблицы несёт
    -- свои скобки. И только при скобке в тексте и полях, из которых есть
    -- что взять: почти все сообщения в репозитории заполнителей не содержат
    -- и платить за поиск не должны — как строка без `:` и `=` не платит
    -- за образцы тайн. Предпроверка на ответ не влияет, только на цену,
    -- и проверки следят за ней счётом вызовов. Скобка ищется без признака
    -- поиска подстроки: в образце она значит себя.
    if textual and record.fields ~= nil and message:find('{') ~= nil then
        message = filled(message, record.fields)
    end

    record.message = note(cut(message, STRING_LIMIT, state), state)

    if instance_name ~= nil then
        record.instance_name = note(instance_name, state)
    end

    if state.truncated then
        record.truncated = true
    end

    -- Точный замер — только там, где оценка не ручается за размер: он стоит
    -- как ещё одна запись.
    local ceiling = state.raw * ESCAPE_GROWTH
    local trusted = ceiling <= RECORD_LIMIT

    if state.overflow or not trusted and #measure.encode(record) > RECORD_LIMIT then
        -- Запасная запись — без полей и без лишних аргументов: её задача
        -- сказать, что было, а не пересказать. Управляющие знаки заменяются,
        -- а не экранируются: `\u0001` вшестеро длиннее знака, и запасная
        -- запись вышла бы за тот же потолок. Опознаватели запроса и трассы
        -- остаются: они коротки, а запись о том, что не влезло, нужна
        -- именно там, где ищут запрос.
        local fallback = {
            message = cut((record.message:gsub('%c', '?')), FALLBACK_LIMIT, state),
            instance_name = instance_name,
            truncated = true,
        }

        for _, name in ipairs(context.LOG_TOP) do
            fallback[name] = record[name]
        end

        return fallback
    end

    return record
end

--- Тело записи в виде plain: сообщение и пары `ключ=значение`.
---
--- Порядок пар и место контекста — в `tnt/log/plain.lua`.
Module.render = plain.render

--- Уровень, начиная с которого журнал модуля молчит.
---
--- Карта модулей у ядра плоская: `tnt: debug` на `tnt.pool` не действует,
--- и имя сверяется целиком. Модуль вне карты получает глобальный уровень.
---@param settings TntLogSettings
---@param name string
---@return integer
local function threshold(settings, name)
    local modules = settings.modules
    local value = type(modules) == 'table' and modules[name] or nil

    if type(value) ~= 'string' and type(value) ~= 'number' then
        value = settings.level
    end

    if type(value) == 'string' then
        value = SEVERITY[value]
    end

    if type(value) ~= 'number' then
        return DEFAULT_LEVEL
    end

    return value
end

--- Отдаёт запись ядру.
---@param current table Действующие средства
---@param settings TntLogSettings
---@param name string
---@param method string
---@param record TntLogRecord
local function emit(current, settings, name, method, record)
    ---@type TntLogRecord|string
    local shown = record

    if settings.format == 'plain' then
        shown = Module.render(record)
    end

    -- Только хвостовой вызов: код после него или pcall вокруг него
    -- переведут file/line всех записей внутрь tnt/log.lua.
    return current.logger(name)[method](shown)
end

--- Каким должно быть имя журнала — словами, для текста отказа.
Module.NAME_RULE =
    'до 128 байт из латиницы, цифр, точки, подчёркивания и дефиса'

--- Годится ли значение в имя журнала.
---
--- Годное — слово из латиницы, цифр, точки, подчёркивания и дефиса
--- не длиннее 128 байт. Имя ядро пишет в заголовок каждой записи мимо
--- фасада: длинное пробило бы потолок записи, кавычка и перевод строки
--- ломали бы plain, а невалидный UTF-8 — строгий JSON.
---
--- Правило отдаётся наружу для тех, кто принимает имя журнала в своей
--- настройке — скажем, меткой слоя: своя копия правила однажды разошлась
--- бы с этой, и негодная метка обнаружилась бы не при настройке, а при
--- сборке первого слоя.
---@param name any
---@return boolean
function Module.is_name(name)
    return type(name) == 'string' and name:find('^[%w%._%-]+$') ~= nil and #name <= NAME_LIMIT
end

--- Проверяет имя журнала.
---
--- Негодное имя — ошибка сборки, а не повод писать в журнал без имени:
--- такой журнал нельзя ни настроить уровнем, ни найти.
---@param name any
local function checked(name)
    if not Module.is_name(name) then
        local refusal = ('имя журнала — %s, например tnt.pool, а не %q'):format(
            Module.NAME_RULE,
            tostring(name)
        )

        -- Уровень 3 указывает на того, кто позвал new или changes: они
        -- передают сюда хвостовым вызовом, и своих кадров у них нет.
        error(refusal, 3)
    end
end

--- Журнал с общей для всех методов частью: уровень, сборка, передача.
---@param name any
---@param write fun(current: table, settings: TntLogSettings, name: string, method: string, record: TntLogRecord): any
---@return TntLogger
local function journal(name, write)
    checked(name)

    local logger = {}

    for _, method in ipairs(METHODS) do
        local severity = SEVERITY[method]

        logger[method] = function(msg, fields, ...)
            local current = source()
            local settings = current.settings()

            -- Уровень сверяется до сборки: отброшенная запись иначе стоила бы
            -- полторы микросекунды обхода полей, а их в отладке тысячи.
            if severity > threshold(settings, name) then
                return
            end

            return write(
                current,
                settings,
                name,
                method,
                build(msg, fields, current.instance_name(), current.context(), ...)
            )
        end
    end

    return logger --[[@as TntLogger]]
end

--- Журнал модуля.
---
--- Имя дословно уходит ядру и в поле `module`: фасад ничего к нему
--- не приписывает, и уровень в конфигурации задаётся ровно этим именем.
---@param name string Полное имя модуля, например tnt.pool
---@return TntLogger
function Module.new(name)
    return journal(name, emit)
end

--- Журнал, в котором подряд идущие повторы не пишутся.
---
--- Циклический агент рассказывает о своей беде каждый такт: за минуту
--- молчащего хранилища в журнале набирается шестьдесят одинаковых строк,
--- и настоящие события тонут между ними. Здесь повтор подавляется, а когда
--- запись наконец меняется, к новой добавляется поле `suppressed` — сколько
--- раз повторилась прежняя.
---
--- Подавляется только повтор подряд: запись, вернувшаяся после другой,
--- пишется снова. Серия одна на все уровни журнала, а отпечаток берётся
--- с уже очищенной записи — кольцо в полях его больше не роняет.
---
--- Поле `suppressed` добавляется после замера размера: оно не длиннее
--- тридцати байт, и запас буфера ядра над потолком записи его покрывает.
---@param name string Полное имя модуля, например tnt.failover
---@return TntLogger
function Module.changes(name)
    local previous = nil

    -- Пусто, а не ноль: «серии не было» и «серия кончилась» — разные
    -- состояния, и различать их числом значило бы считать до нуля там,
    -- где считать нечего.
    local suppressed = nil

    return journal(name, function(current, settings, _, method, record)
        -- Имя инстанса и поля контекста в отпечаток не входят: одна и та же
        -- беда в двух запросах даёт разные `request_id`, и повтор иначе
        -- не узнавался бы никогда.
        local signature = method .. ':' .. plain.fingerprint(record)

        if signature == previous then
            suppressed = (suppressed or 0) + 1

            return
        end

        previous = signature
        record.suppressed = suppressed
        suppressed = nil

        return emit(current, settings, name, method, record)
    end)
end

return Module
