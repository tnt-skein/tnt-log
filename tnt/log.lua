local CUT = '…'

--- Потолок строки в байтах. Сообщение в 4 КБ человек уже не читает,
--- а 1 МБ, пришедший ответом чужого сервера, иначе занял бы весь буфер ядра.
local STRING_LIMIT = 4096

--- Сколько байт строки проходят образцами тайн.
---
--- Образцы написаны так, чтобы идти за линейное время, но окно — вторая
--- линия защиты: образец, который однажды поправят неудачно, на мегабайте
--- `a:a:a:…` шёл бы часами, и запись в журнал повесила бы узел.
---
--- Окно вдвое шире потолка строки: вырезание тайн укорачивает строку,
--- и в запись из 4096 байт может попасть то, что лежало дальше 4096-го.
--- За окном не попадает ничего, а имя тайны стоит перед значением: если
--- значение в запись попало, его имя образцы видели. Окно обрезает только
--- хвосты. Значение в кавычках, закрытых за окном, прячется до конца окна
--- как незакрытое. Пароль адреса, у которого `@` лежит за окном,
--- не узнаётся — он должен быть длиннее окна за вычетом спрятанного перед
--- ним. Строка длиннее окна считается урезанной, даже если после
--- вырезания тайн она стала короткой: целиком её никто не видел.
local SCRUB_WINDOW = 2 * STRING_LIMIT

--- Потолок имени журнала в байтах. Имя ядро пишет в каждую запись мимо
--- фасада, и имя в пару килобайт пробило бы потолок записи.
local NAME_LIMIT = 128

--- Предел вложенности. Ядро пропускает 128 вложенных таблиц и бросает
--- на 129-й, а человек теряет нить куда раньше.
local MAX_DEPTH = 16

--- Потолок JSON записи, отданной ядру.
---
--- Буфер записи у ядра ~16 КБ, а свой заголовок оно дописывает до ~300
--- байт. Больше — и ядро режет таблицу с NUL внутри, а в plain строка
--- уходит без перевода строки и склеивается со следующей.
local RECORD_LIMIT = 15000

--- Потолок сообщения в запасной записи. Её задача — сказать, что было,
--- а не пересказать; тысячи байт на это хватает.
local FALLBACK_LIMIT = 1024

--- Сколько проверенных имён помнить.
---
--- Имена приходят и из данных — заголовки, ключи чужих таблиц, — и без
--- потолка память росла бы с каждым новым заголовком.
local MEMO_LIMIT = 1024

--- Сколько байт в самом длинном имени, которое помнится.
---
--- Имя поля или заголовка укладывается в десятки байт. Без потолка
--- тысяча ключей по 8 КБ держала бы в памяти 8 МБ.
local MEMO_NAME_LIMIT = 128

--- Сколько байт оценки положено на одно значение сверх его текста.
---
--- Оценка грубая и нужна для двух решений. Во-первых, остановить обход,
--- как только запись заведомо велика: таблица из 60000 ключей иначе
--- обходилась бы вся ради запасной записи. Во-вторых, не делать точный
--- замер там, где он заведомо не нужен. Для второго оценка, умноженная
--- на рост экранирования, обязана быть верхней границей JSON: кавычки,
--- двоеточие и запятая вокруг строки — это три байта, а число или ключ-
--- число в JSON не длиннее 24 знаков, то есть четырёх байт оценки.
local PIECE = 4

